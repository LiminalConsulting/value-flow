/**
 * anonymize.ts — writes data.anon.ts from data.ts: the same group, nothing
 * that names it. `bun anonymize.ts` (rerun whenever data.ts changes).
 *
 * Kept: every count, category, status, certainty, flow, rate, partner and
 * role — the picture is the same in structure. Changed: the group is
 * "Group"; plant codes become S01…S20 in data.ts's order; entity names,
 * notes and the former name are dropped; every place (plants and the
 * holding) snaps to the centre of its 2° × 2° cell, and sites sharing a
 * cell sit on a 0.5° ring round it (evenly spaced) — country-scale, never a
 * town. Generic partner labels stay as they are.
 *
 * The standalone build (core/scripts/build-standalone.ts --data=anon) swaps
 * data.ts for data.anon.ts.
 */

import { BLUE, RED } from "../../core/src/constants"
import { FAMILY_OF, FLOWMAP, GROUP, PLANTS, ROLES, SHOWCASE } from "./data"

const code = new Map(PLANTS.map((p, i) => [p.code, `S${String(i + 1).padStart(2, "0")}`]))
/** A string as the anonymous data spells it: a code, or a role id ending in one. */
const swap = (s: string): string => {
  const exact = code.get(s)
  if (exact) return exact
  const m = /^(.*-)([A-Z]{3})$/.exec(s)
  return m && code.has(m[2]!) ? m[1]! + code.get(m[2]!)! : s
}

const CELL = 2
const cellOf = (lat: number, lon: number) => [Math.floor(lat / CELL) * CELL + CELL / 2, Math.floor(lon / CELL) * CELL + CELL / 2] as const
/** Every place: the plants, then the holding (index PLANTS.length). */
const places = [...PLANTS, GROUP]
const cells = new Map<string, number[]>()
places.forEach((p, i) => {
  const k = cellOf(p.lat, p.lon).join()
  cells.set(k, [...(cells.get(k) ?? []), i])
})
const r2 = (x: number) => Math.round(x * 100) / 100
const placeOf = (i: number): { lat: number; lon: number } => {
  const p = places[i]!
  const [lat, lon] = cellOf(p.lat, p.lon)
  const mates = cells.get([lat, lon].join())!
  if (mates.length === 1) return { lat, lon }
  const a = (2 * Math.PI * mates.indexOf(i)) / mates.length
  return { lat: r2(lat + 0.5 * Math.cos(a)), lon: r2(lon + 0.5 * Math.sin(a)) }
}

const plants = PLANTS.map((p, i) => ({
  code: swap(p.code),
  categories: p.categories,
  ...placeOf(i),
  located: p.located,
  ...(p.status ? { status: p.status } : {}),
}))
const { lat: glat, lon: glon } = placeOf(PLANTS.length)

/** JSON, but a colour is its constant's name and strings are swapped. */
const lit = (v: unknown, indent = ""): string => {
  if (v === RED) return "RED"
  if (v === BLUE) return "BLUE"
  if (typeof v === "string") return JSON.stringify(swap(v))
  if (Array.isArray(v) && v.every((x) => typeof x !== "object")) return `[${v.map((x) => lit(x)).join(", ")}]`
  if (Array.isArray(v)) return v.length ? `[\n${v.map((x) => `${indent}  ${lit(x, indent + "  ")},`).join("\n")}\n${indent}]` : "[]"
  if (v && typeof v === "object")
    return `{ ${Object.entries(v)
      .filter(([, x]) => x !== undefined)
      .map(([k, x]) => `${JSON.stringify(swap(k))}: ${lit(x, indent)}`)
      .join(", ")} }`
  return JSON.stringify(v)
}

const flowmap = {
  categories: FLOWMAP.categories,
  members: plants.map((p) => ({ id: p.code, label: p.code, categories: p.categories })),
  partners: FLOWMAP.partners,
  stages: FLOWMAP.stages,
  flows: FLOWMAP.flows,
}
const inScope = (ROLES.sites ?? []).map(swap)

const out = `/**
 * data.anon.ts — GENERATED by anonymize.ts from data.ts; do not edit.
 * The same group in structure, with nothing that names it.
 */

import type { FlowMapData } from "../../core/vocabulary/FlowMap/FlowMap"
import { BLUE, RED } from "../../core/src/constants"
import type { RoleMapData } from "../../core/vocabulary/RoleMap/RoleMap"

export type Category = "conversion" | "extrusion"

export interface Plant {
  code: string
  categories: Category[]
  lat: number
  lon: number
  located: number
  status?: "closed" | "closing"
  entity?: string
  note?: string
}

export const GROUP = { name: "Group", lat: ${glat}, lon: ${glon}, located: ${GROUP.located} }

export const CATEGORY_TINT: Record<Category, typeof RED> = { conversion: RED, extrusion: BLUE }

export const PLANTS: Plant[] = ${lit(plants)}

export const FLOWMAP: FlowMapData = ${lit(flowmap)}

export const SHOWCASE = { lens: ${lit(SHOWCASE.lens)}, fiber: ${lit(SHOWCASE.fiber)} as const, inside: ${lit(SHOWCASE.inside)} }

export const FAMILY_OF: Partial<Record<string, "ERP A" | "ERP B" | "ERP C" | "ERP D">> = ${lit(FAMILY_OF)}

export const IN_SCOPE: string[] = ${lit(inScope)}

export const ROLES: RoleMapData = ${lit(ROLES)}
`

await Bun.write(new URL("./data.anon.ts", import.meta.url), out)
// Nothing that names the group may survive: no plant code, no name.
const leaks = [...code.keys(), GROUP.name, ...PLANTS.flatMap((p) => [p.entity ?? "", p.note ?? ""]).filter(Boolean)].filter((s) => new RegExp(`\\b${s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`).test(out))
if (leaks.length) {
  console.error(`data.anon.ts still holds: ${leaks.join(", ")}`)
  process.exit(1)
}
console.log(`data.anon.ts written · ${plants.length} sites · ${FLOWMAP.flows.length} flows · ${cells.size} cells`)
